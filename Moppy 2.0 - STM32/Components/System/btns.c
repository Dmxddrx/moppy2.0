#include "btns.h"

// Define how many milliseconds the button must remain stable to clear electrical noise
#define DEBOUNCE_TIME_MS 20

// Internal state tracking for K0
static bool k0_last_read = true;
static bool k0_stable_state = true;
static uint32_t k0_debounce_timer = 0;
static bool k0_pressed_event = false;

// Internal state tracking for K1
static bool k1_last_read = true;
static bool k1_stable_state = true;
static uint32_t k1_debounce_timer = 0;
static bool k1_pressed_event = false;

void BTNS_Init(void)
{
    // The hardware GPIO initialization is already handled by MX_GPIO_Init()
    // generated by CubeMX. We just reset the software state variables here.
    k0_last_read = true;
    k0_stable_state = true;
    k0_pressed_event = false;

    k1_last_read = true;
    k1_stable_state = true;
    k1_pressed_event = false;
}

void BTNS_Update(void)
{
    // Use the HAL system tick for non-blocking timing
    uint32_t current_time = HAL_GetTick();

    /* ==================================================================== */
    /* Process K0 (PE2)                                                     */
    /* ==================================================================== */
    // Note: Due to Pull-up configuration, GPIO_PIN_SET means the button is RELEASED.
    bool k0_current_read = (HAL_GPIO_ReadPin(K0_GPIO_Port, K0_Pin) == GPIO_PIN_SET);

    // If the raw pin state changes (due to a press or noise), reset the timer
    if (k0_current_read != k0_last_read) {
        k0_debounce_timer = current_time;
    }

    // If the state has remained consistent longer than the debounce threshold
    if ((current_time - k0_debounce_timer) > DEBOUNCE_TIME_MS) {
        if (k0_current_read != k0_stable_state) {
            k0_stable_state = k0_current_read;

            // If the newly stable state transitioned from HIGH to LOW (pressed down)
            if (k0_stable_state == false) {
                k0_pressed_event = true;
            }
        }
    }
    k0_last_read = k0_current_read;

    /* ==================================================================== */
    /* Process K1 (PE3)                                                     */
    /* ==================================================================== */
    bool k1_current_read = (HAL_GPIO_ReadPin(K1_GPIO_Port, K1_Pin) == GPIO_PIN_SET);

    if (k1_current_read != k1_last_read) {
        k1_debounce_timer = current_time;
    }

    if ((current_time - k1_debounce_timer) > DEBOUNCE_TIME_MS) {
        if (k1_current_read != k1_stable_state) {
            k1_stable_state = k1_current_read;

            if (k1_stable_state == false) {
                k1_pressed_event = true;
            }
        }
    }
    k1_last_read = k1_current_read;
}

bool BTNS_IsK0_Pressed(void)
{
    // Check if a press event occurred
    if (k0_pressed_event) {
        k0_pressed_event = false; // Clear the flag immediately so it only triggers once
        return true;
    }
    return false;
}

bool BTNS_IsK1_Pressed(void)
{
    if (k1_pressed_event) {
        k1_pressed_event = false;
        return true;
    }
    return false;
}

bool BTNS_IsK0_Held(void)
{
    // Since it's pulled up, a stable state of 'false' (LOW) means it is currently being held
    return !k0_stable_state;
}

bool BTNS_IsK1_Held(void)
{
    return !k1_stable_state;
}
